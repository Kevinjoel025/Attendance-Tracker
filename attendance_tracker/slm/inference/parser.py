"""
slm/inference/parser.py
───────────────────────
Structured output parser for Attendance SLM completions.

Parses the 5-field pipe-delimited format:
    INTENT|SUBJECT|TARGET|COUNT|DATE

Rules:
- Validates the 8 canonical intents.
- Normalizes "NONE" / empty tokens to Python None.
- Casts TARGET to float and COUNT to int safely.
- Never raises uncaught exceptions on malformed model outputs.
- Captures validation status and detailed malformed reasons.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional, Set

VALID_INTENTS: Set[str] = {
    "GET_ATTENDANCE",
    "GET_SUBJECT_ATTENDANCE",
    "ATTENDANCE_PROJECTION",
    "CLASSES_REQUIRED_FOR_TARGET",
    "MAX_CLASSES_CAN_MISS",
    "CHECK_ATTENDANCE_UPDATE",
    "HELP",
    "UNKNOWN",
}


@dataclass(frozen=True)
class ParsedNLUOutput:
    """Structured representation of parsed SLM completion."""

    intent: str
    subject: Optional[str]
    target: Optional[float]
    count: Optional[int]
    date: Optional[str]
    is_valid: bool
    malformed_reason: Optional[str] = None
    raw_output: str = ""


def parse_nlu_output(raw_output: str) -> ParsedNLUOutput:
    """
    Parse a 5-position pipe-delimited completion string into a structured ParsedNLUOutput.

    Expected format:
        INTENT|SUBJECT|TARGET|COUNT|DATE

    Parameters
    ----------
    raw_output : str
        The raw text completion generated by the SLM.

    Returns
    -------
    ParsedNLUOutput
        Parsed and validated output object.
    """
    cleaned = raw_output.strip() if raw_output else ""
    if not cleaned:
        return ParsedNLUOutput(
            intent="UNKNOWN",
            subject=None,
            target=None,
            count=None,
            date=None,
            is_valid=False,
            malformed_reason="Empty output string",
            raw_output=raw_output,
        )

    parts = [p.strip() for p in cleaned.split("|")]
    if len(parts) != 5:
        # Fallback intent extraction if possible
        candidate_intent = parts[0].upper() if parts and parts[0].upper() in VALID_INTENTS else "UNKNOWN"
        return ParsedNLUOutput(
            intent=candidate_intent,
            subject=None,
            target=None,
            count=None,
            date=None,
            is_valid=False,
            malformed_reason=f"Expected 5 pipe-delimited fields, got {len(parts)}: '{cleaned}'",
            raw_output=raw_output,
        )

    raw_intent, raw_subject, raw_target, raw_count, raw_date = parts

    is_valid = True
    reasons: list[str] = []

    # 1. Validate Intent
    intent_norm = raw_intent.upper()
    if intent_norm not in VALID_INTENTS:
        is_valid = False
        reasons.append(f"Unrecognized intent '{raw_intent}'")
        intent = "UNKNOWN"
    else:
        intent = intent_norm

    # 2. Parse Subject
    subject: Optional[str] = None
    if raw_subject and raw_subject.upper() != "NONE":
        subject = raw_subject

    # 3. Parse Target
    target: Optional[float] = None
    if raw_target and raw_target.upper() != "NONE":
        # Handle trailing percentage signs if present
        clean_target = raw_target.rstrip("%").strip()
        try:
            target = float(clean_target)
        except ValueError:
            is_valid = False
            reasons.append(f"Invalid numeric target '{raw_target}'")

    # 4. Parse Count
    count: Optional[int] = None
    if raw_count and raw_count.upper() != "NONE":
        try:
            count = int(raw_count)
        except ValueError:
            is_valid = False
            reasons.append(f"Invalid integer count '{raw_count}'")

    # 5. Parse Date
    date_val: Optional[str] = None
    if raw_date and raw_date.upper() != "NONE":
        date_val = raw_date

    malformed_reason = "; ".join(reasons) if not is_valid else None

    return ParsedNLUOutput(
        intent=intent,
        subject=subject,
        target=target,
        count=count,
        date=date_val,
        is_valid=is_valid,
        malformed_reason=malformed_reason,
        raw_output=raw_output,
    )
